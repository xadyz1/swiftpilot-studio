import type { ContentTemplate, Tone, VisualLayout } from './content';

type LanguageCopy = Record<'en' | 'pt', string>;

interface DraftSeed {
  id: string;
  title: LanguageCopy;
  headline: LanguageCopy;
  overlay: LanguageCopy;
  caption: LanguageCopy;
  hashtags: LanguageCopy;
  cta: LanguageCopy;
  notes: LanguageCopy;
  campaign: string;
  theme: string;
  image: string;
  sourceUrl: string;
  tone: Tone;
  layout: VisualLayout;
}

function localizedDrafts(projectId: string, drafts: DraftSeed[]): ContentTemplate[] {
  return drafts.flatMap(draft => (['pt', 'en'] as const).map(language => {
    const outputNotes = language === 'pt'
      ? 'Exporta um post quadrado 1:1 e uma versão 9:16 para Stories/Reels; mantém o texto na área central segura dos Stories.'
      : 'Export a square 1:1 feed post and a 9:16 Story/Reel master; keep text inside the central safe area for Stories.';
    const notes = `${draft.notes[language]} ${outputNotes}`;
    const variant = {
      caption: draft.caption[language],
      hashtags: draft.hashtags[language],
      cta: draft.cta[language],
      notes,
    };
    return {
      id: `${projectId}-${draft.id}-${language}`,
      language,
      title: `${draft.title[language]} · ${language.toUpperCase()}`,
      headline: draft.headline[language],
      eyebrow: language === 'pt' ? 'PORTUGUÊS' : 'ENGLISH',
      supportingCopy: draft.overlay[language],
      cta: draft.cta[language],
      campaign: draft.campaign,
      theme: draft.theme,
      format: 'Image' as const,
      platforms: ['instagram'],
      image: draft.image,
      mediaKind: 'image' as const,
      sourceUrl: draft.sourceUrl,
      tone: draft.tone,
      layout: draft.layout,
      aspectRatio: 'square' as const,
      showLogo: true,
      variants: { instagram: variant, tiktok: variant },
    };
  }));
}

